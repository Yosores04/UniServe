import request from "supertest";
import { describe, expect, it } from "vitest";
import { createApp } from "./app.js";
import { prisma } from "./db/prisma.js";

const app = createApp();
async function login(email: string, password: string) {
  const agent = request.agent(app);
  expect((await agent.post("/api/auth/login").send({ email, password })).status).toBe(200);
  return agent;
}
async function register(role: string) {
  const agent = request.agent(app);
  expect((await agent.post("/api/auth/register").send({ name: "Test Person", email: `${role.toLowerCase()}-${crypto.randomUUID()}@test.local`, password: "Password123!", role })).status).toBe(201);
  return agent;
}
describe("Shared marketplace", () => {
  it("isolates logout to the requesting phone", async () => {
    const first = await login("customer@uniserve.local", "Customer123!");
    const second = await login("customer@uniserve.local", "Customer123!");
    expect((await first.post("/api/auth/logout")).status).toBe(204);
    expect((await second.get("/api/auth/me")).status).toBe(200);
  });
  it("runs seller onboarding, scoped orders, atomic claims, ordered delivery, chat, ratings and complaints", async () => {
    const admin = await login("admin@uniserve.local", "Admin123!");
    const buyer = await register("CUSTOMER");
    const stranger = await register("CUSTOMER");
    const seller = await register("SHOP");
    const courier = await register("RIDER");
    const rival = await register("RIDER");
    const initial = await seller.get("/api/workspace");
    expect(initial.status).toBe(200);
    expect(initial.body).toMatchObject({ shops: [], orders: [], rider: null, riders: [], users: [], complaints: [] });
    const created = await seller.post("/api/shop/profile").send({ name: " Campus Crafts ", category: "Student goods", location: "Library", operatingHours: "8 AM - 5 PM" });
    expect(created.status).toBe(201);
    const shopId = created.body.shop.id;
    expect(created.body.shop.name).toBe("Campus Crafts");
    expect((await buyer.get("/api/workspace")).body.shops.some((s: any) => s.id === shopId)).toBe(false);
    expect((await admin.patch(`/api/admin/shops/${shopId}/verification`).send({ verification: "VERIFIED" })).status).toBe(200);
    const product = await seller.post("/api/shop/items").send({ name: "Notebook", price: 60 });
    expect(product.status).toBe(201);
    const itemId = product.body.item.id;
    expect((await seller.patch(`/api/shop/items/${itemId}`).send({ price: 75 })).status).toBe(200);
    const payload = { shopId, serviceType: "Marketplace", pickupPoint: " Library ", dropoffPoint: "COT", paymentMethod: "COD", items: [{ shopItemId: itemId, quantity: 2 }], total: 1 };
    expect((await buyer.post("/api/customer/orders").send({ ...payload, serviceType: "MadeUp" })).status).toBe(400);
    const placed = await buyer.post("/api/customer/orders").send(payload);
    expect(placed.status).toBe(201);
    expect(placed.body.order.total).toBe(175);
    const id = placed.body.order.id;
    expect((await stranger.get(`/api/customer/orders/${id}`)).status).toBe(404);
    expect((await stranger.post(`/api/customer/orders/${id}/messages`).send({ content: "intrusion" })).status).toBe(404);
    expect((await buyer.post(`/api/customer/orders/${id}/messages`).send({ content: " Meet at lobby " })).status).toBe(201);
    expect((await seller.patch(`/api/shop/orders/${id}/status`).send({ status: "READY_FOR_PICKUP" })).status).toBe(409);
    expect((await seller.patch(`/api/shop/orders/${id}/status`).send({ status: "COMPLETED" })).status).toBe(409);
    for (const rider of [courier, rival]) {
      const profile = (await rider.get("/api/workspace")).body.rider;
      expect((await admin.patch(`/api/admin/riders/${profile.id}/verification`).send({ verified: true })).status).toBe(200);
      await rider.patch("/api/rider/availability").send({ availability: "ONLINE" });
    }
    const claims = await Promise.all([courier.post(`/api/rider/jobs/${id}/accept`), rival.post(`/api/rider/jobs/${id}/accept`)]);
    expect(claims.map(c => c.status).sort()).toEqual([200, 409]);
    const winner = claims[0].status === 200 ? courier : rival;
    const loser = claims[0].status === 200 ? rival : courier;
    expect((await loser.post(`/api/rider/deliveries/${id}/messages`).send({ content: "intrusion" })).status).toBe(404);
    expect((await winner.patch(`/api/rider/deliveries/${id}/status`).send({ status: "DELIVERED" })).status).toBe(409);
    expect((await winner.patch(`/api/rider/deliveries/${id}/status`).send({ status: "PICKED_UP" })).status).toBe(409);
    expect((await buyer.post(`/api/customer/orders/${id}/cancel`)).status).toBe(409);
    expect((await seller.patch(`/api/shop/orders/${id}/status`).send({ status: "PREPARING" })).status).toBe(200);
    expect((await seller.patch(`/api/shop/orders/${id}/status`).send({ status: "READY_FOR_PICKUP" })).status).toBe(200);
    expect((await winner.post(`/api/rider/deliveries/${id}/messages`).send({ content: "On my way" })).status).toBe(201);
    for (const status of ["PICKED_UP", "ON_THE_WAY", "DELIVERED"]) expect((await winner.patch(`/api/rider/deliveries/${id}/status`).send({ status })).status).toBe(200);
    expect((await winner.patch(`/api/rider/deliveries/${id}/status`).send({ status: "DELIVERED" })).status).toBe(409);
    expect((await winner.get("/api/workspace")).body.rider).toMatchObject({ earningsToday: 25, deliveriesToday: 1 });
    const winningProfile = (await winner.get("/api/workspace")).body.rider;
    await prisma.riderProfile.update({ where: { id: winningProfile.id }, data: { earningsToday: 9999, deliveriesToday: 99 } });
    expect((await winner.get("/api/rider/profile")).body.profile).toMatchObject({ earningsToday: 25, deliveriesToday: 1 });
    expect((await admin.get("/api/workspace")).body.riders.find((r: any) => r.id === winningProfile.id)).toMatchObject({ earningsToday: 25, deliveriesToday: 1 });
    expect((await buyer.post(`/api/customer/orders/${id}/rating`).send({ score: 5 })).status).toBe(201);
    await prisma.shop.update({ where: { id: shopId }, data: { salesToday: 9999, rating: 1 } });
    expect((await buyer.get("/api/workspace")).body.shops.find((s: any) => s.id === shopId).salesToday).toBe(150);
    expect((await buyer.get("/api/workspace")).body.shops.find((s: any) => s.id === shopId).rating).toBe(5);
    const complaint = await buyer.post(`/api/customer/orders/${id}/complaint`).send({ subject: "Packaging", detail: "Please use less packaging" });
    expect(complaint.status).toBe(201);
    expect((await admin.patch(`/api/admin/complaints/${complaint.body.complaint.id}`).send({ status: "RESOLVED", resolution: "Shared feedback" })).status).toBe(200);
    const snapshot = (await buyer.get("/api/workspace")).body;
    expect(snapshot.orders).toHaveLength(1);
    expect(snapshot.orders[0].chatThread.messages).toHaveLength(2);
    expect(snapshot.orders[0].shopStatus).toBe("COMPLETED");
    expect((await seller.get("/api/workspace")).body.shops.map((s: any) => s.id)).toEqual([shopId]);
    for (const path of ["/api/workspace", "/api/admin/orders", "/api/admin/shops", "/api/admin/riders", "/api/admin/complaints"]) expect((await admin.get(path)).text).not.toContain("passwordHash");
    expect((await seller.get("/api/shop/orders")).text).not.toContain("passwordHash");
    expect((await courier.get("/api/rider/profile")).text).not.toContain("passwordHash");
    const cancelled = await buyer.post("/api/customer/orders").send(payload);
    expect((await buyer.post(`/api/customer/orders/${cancelled.body.order.id}/cancel`)).status).toBe(200);
    expect((await seller.patch(`/api/shop/orders/${cancelled.body.order.id}/status`).send({ status: "PREPARING" })).status).toBe(409);
    expect((await admin.get("/api/admin/reports/overview")).body.totals.revenue).toBe(175);
  });
  it("scopes seller catalog writes, hides pending customer details, rejects unavailable products and races cancellation with claim", async () => {
    const admin = await login("admin@uniserve.local", "Admin123!");
    const seller = await register("SHOP");
    const otherSeller = await register("SHOP");
    const buyer = await register("CUSTOMER");
    const rider = await register("RIDER");
    const shop = (await seller.post("/api/shop/profile").send({ name: "Print test", category: "Printing", location: "Library", operatingHours: "8 to 5" })).body.shop;
    await admin.patch(`/api/admin/shops/${shop.id}/verification`).send({ verification: "VERIFIED" });
    const item = (await seller.post("/api/shop/items").send({ name: "Page", price: 5 })).body.item;
    expect((await otherSeller.patch(`/api/shop/items/${item.id}`).send({ price: 1 })).status).toBe(404);
    expect((await otherSeller.get("/api/shop/orders")).body.orders).toEqual([]);
    expect((await seller.post("/api/shop/items").send({ name: "   ", price: 5 })).status).toBe(400);
    expect((await seller.patch(`/api/shop/items/${item.id}`).send({ price: 0.5 })).status).toBe(400);
    const payload = { shopId: shop.id, serviceType: "Printing", pickupPoint: "Library", dropoffPoint: "COT", paymentMethod: "COD", items: [{ shopItemId: item.id, quantity: 2 }] };
    await seller.patch(`/api/shop/items/${item.id}`).send({ available: false });
    expect((await buyer.post("/api/customer/orders").send(payload)).status).toBe(400);
    await seller.patch(`/api/shop/items/${item.id}`).send({ available: true });
    await seller.patch("/api/shop/profile").send({ open: false });
    expect((await buyer.post("/api/customer/orders").send(payload)).status).toBe(404);
    await seller.patch("/api/shop/profile").send({ open: true });
    expect((await buyer.post("/api/customer/orders").send({ ...payload, dropoffPoint: " Library " })).status).toBe(400);
    const order = (await buyer.post("/api/customer/orders").send(payload)).body.order;
    const spoofed = (await buyer.post("/api/customer/orders").send({ ...payload, pickupPoint: "Spoofed pickup" })).body.order;
    expect(spoofed.pickupPoint).toBe(shop.location);
    expect((await buyer.post(`/api/customer/orders/${order.id}/rating`).send({ score: 5 })).status).toBe(400);
    await buyer.post(`/api/customer/orders/${order.id}/messages`).send({ content: "Private delivery instruction" });
    const queue = (await rider.get("/api/workspace")).body.orders.find((o: any) => o.id === order.id);
    for (const key of ["customer", "customerId", "customerNote", "chatThread"]) expect(queue).not.toHaveProperty(key);
    expect((await rider.get("/api/rider/jobs")).text).not.toContain("customerId");
    const profile = (await rider.get("/api/workspace")).body.rider;
    expect((await rider.post(`/api/rider/jobs/${order.id}/accept`)).status).toBe(400);
    await admin.patch(`/api/admin/riders/${profile.id}/verification`).send({ verified: true });
    await rider.patch("/api/rider/availability").send({ availability: "ONLINE" });
    const results = await Promise.all([buyer.post(`/api/customer/orders/${order.id}/cancel`), rider.post(`/api/rider/jobs/${order.id}/accept`)]);
    expect(results.map(result => result.status).sort()).toEqual([200, 409]);
    const saved = await prisma.order.findUniqueOrThrow({ where: { id: order.id }, include: { delivery: true } });
    expect(saved.status === "CANCELLED" ? saved.delivery === null && saved.riderId === null : saved.delivery?.riderId === saved.riderId).toBe(true);
    expect((await request(app).get("/api/workspace")).status).toBe(401);
    expect((await buyer.patch(`/api/admin/riders/${profile.id}/verification`).send({ verified: false })).status).toBe(403);
    await seller.patch(`/api/shop/items/${item.id}`).send({ price: 1000000 });
    const excessive = { ...payload, items: Array.from({ length: 50 }, () => ({ shopItemId: item.id, quantity: 100 })) };
    expect((await buyer.post("/api/customer/orders").send(excessive)).status).toBe(400);
    await admin.patch(`/api/admin/users/${shop.ownerId}/status`).send({ active: false });
    expect((await buyer.get("/api/customer/shops")).body.shops.some((s: any) => s.id === shop.id)).toBe(false);
    expect((await buyer.get("/api/workspace")).body.shops.some((s: any) => s.id === shop.id)).toBe(false);
    expect((await buyer.post("/api/customer/orders").send(payload)).status).toBe(404);
  });
});
